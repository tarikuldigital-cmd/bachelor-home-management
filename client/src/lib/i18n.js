let lang = localStorage.getItem('bhm_lang') || 'en';
export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  localStorage.setItem('bhm_lang', l);
}
export function t(key, vars) {
  const e = D[key];
  let s = e ? e[lang === 'en' ? 1 : 0] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}
const BN = '০১২৩৪৫৬৭৮৯';
export function n2(n) {
  const s = String(n);
  return lang === 'bn' ? s.replace(/\d/g, (d) => BN[d]) : s;
}
